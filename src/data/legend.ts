/**
 * Arsenal de légende (Knight Studio, 2025, aide de jeu officielle optionnelle), p. 5-24.
 * Liens relevés sur les arbres : `racine` = réseau relié au châssis ; `bus:…` = ligne commune non reliée au châssis.
 * Les liens sont symétriques (il suffit de les déclarer d'un côté).
 */

const R: Record<'S' | 'A' | 'R' | 'P', Disponibilite> = { S: 'standard', A: 'avance', R: 'rare', P: 'prestige' }

/** Bonus abrégés : `dD1` = +1D6 dégâts, `vF3` = +3 violence… */
function bonus(code?: string): LegendBonus | undefined {
  if (!code) return undefined
  const m = /^([dv])([DF])(\d+)$/.exec(code)!
  const key = `${m[1] === 'd' ? 'degats' : 'violence'}${m[2] === 'D' ? 'Des' : 'Fixe'}` as keyof LegendBonus
  return { [key]: Number(m[3]) }
}

interface Extra {
  b?: string
  effet?: string
  remplace?: string
  retire?: string[]
  portee?: Portee
  texte?: string
}

function o(id: string, nom: string, rarete: keyof typeof R, couts: number[], liens: string[], x: Extra = {}): LegendOptimisation {
  return {
    id,
    nom,
    rarete: R[rarete],
    couts,
    liens,
    ...(x.b ? { bonus: bonus(x.b) } : {}),
    ...(x.effet ? { effet: x.effet } : {}),
    ...(x.remplace ? { remplace: x.remplace } : {}),
    ...(x.retire ? { retire: x.retire } : {}),
    ...(x.portee ? { portee: x.portee } : {}),
    ...(x.texte ? { texte: x.texte } : {}),
  }
}

function profil(type: 'contact' | 'distance', degats: string, violence: string, portee: Portee, effets: string): WeaponProfile {
  return { nom: 'Optimisée', type, degats: parseDice(degats), violence: parseDice(violence), portee, effets: parseEffects(effets) }
}

